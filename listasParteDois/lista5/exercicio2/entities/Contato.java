package entities;

public class Contato {

    private int telefone;
    private String nome;

    public void setTelefone(int tel) {
        telefone = tel;
    }

    public int getTelefone() {
        return telefone;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String n) {
        nome = n;
    }
}
